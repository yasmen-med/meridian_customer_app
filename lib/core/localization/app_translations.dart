extension TranslationExtension on BuildContext {
  String get langCode {
    try {
      return read<LocaleController>().languageCode;
    } catch (_) {
      return 'en';
    }
  }

  String tr(String key) {
    return AppTranslations.tr(key, langCode);
  }

  String trCategory(String category) {
    final key = category.toLowerCase().replaceAll(' ', '_');
    return AppTranslations.tr(key, langCode);
  }
}
